#!/bin/bash
# ============================================
# 构建脚本 - 本地打包
# ============================================

set -e

cd "$(dirname "$0")/.."

echo "========================================"
echo "         开始构建 yasi 前端"
echo "========================================"

# 1. 安装依赖
echo ""
echo "[1/3] 📦 安装依赖..."
pnpm install

# 2. 构建
echo ""
echo "[2/3] 🔨 构建中..."
npm run build

# 3. 打包
echo ""
echo "[3/3] 📁 打包中..."
VERSION=$(date +%Y%m%d_%H%M%S)
tar -czf "yasi_${VERSION}.tar.gz" build/

echo ""
echo "========================================"
echo "✅ 构建完成: yasi_${VERSION}.tar.gz"
echo "========================================"
